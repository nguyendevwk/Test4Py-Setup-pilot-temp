import pytest
from youtube_dl.aes import mix_column, rijndael_mul

# Test 1: Normal operation with a known matrix and data
def test_mix_column_basic():
    data = [0x01, 0x02, 0x03, 0x04]
    matrix = [
        [0x02, 0x03, 0x01, 0x01],
        [0x01, 0x02, 0x03, 0x01],
        [0x01, 0x01, 0x02, 0x03],
        [0x03, 0x01, 0x01, 0x02],
    ]
    result = mix_column(data, matrix)
    expected = [
        rijndael_mul(0x01, 0x02) ^ rijndael_mul(0x02, 0x03) ^ rijndael_mul(0x03, 0x01) ^ rijndael_mul(0x04, 0x01),
        rijndael_mul(0x01, 0x01) ^ rijndael_mul(0x02, 0x02) ^ rijndael_mul(0x03, 0x03) ^ rijndael_mul(0x04, 0x01),
        rijndael_mul(0x01, 0x01) ^ rijndael_mul(0x02, 0x01) ^ rijndael_mul(0x03, 0x02) ^ rijndael_mul(0x04, 0x03),
        rijndael_mul(0x01, 0x03) ^ rijndael_mul(0x02, 0x01) ^ rijndael_mul(0x03, 0x01) ^ rijndael_mul(0x04, 0x02),
    ]
    assert result == expected

# Test 2: Boundary case where all data elements are zero
def test_mix_column_all_zero():
    data = [0x00, 0x00, 0x00, 0x00]
    matrix = [
        [0x02, 0x03, 0x01, 0x01],
        [0x01, 0x02, 0x03, 0x01],
        [0x01, 0x01, 0x02, 0x03],
        [0x03, 0x01, 0x01, 0x02],
    ]
    result = mix_column(data, matrix)
    assert result == [0, 0, 0, 0]

# Test 3: Error handling when data list is too short
def test_mix_column_invalid_length():
    data = [0x01, 0x02]  # only two elements
    matrix = [
        [0x02, 0x03, 0x01, 0x01],
        [0x01, 0x02, 0x03, 0x01],
        [0x01, 0x01, 0x02, 0x03],
        [0x03, 0x01, 0x01, 0x02],
    ]
    with pytest.raises(IndexError):
        mix_column(data, matrix)
