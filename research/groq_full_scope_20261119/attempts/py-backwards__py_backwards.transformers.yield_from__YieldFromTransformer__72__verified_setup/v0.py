import ast as pyast
import typed_ast.ast3 as ast
import pytest
from py_backwards.transformers.yield_from import YieldFromTransformer

def ast_to_code(node: ast.AST) -> str:
    """Helper to convert an AST back to source code for easier inspection."""
    return pyast.unparse(node)

def test_yield_from_assignment_transforms():
    # Original code with a yield-from in an assignment
    source = "x = (yield from iterable)"
    tree = ast.parse(source)
    transformer = YieldFromTransformer()
    transformed = transformer.visit(tree)

    # The transformed tree should no longer contain any YieldFrom nodes
    yield_from_nodes = [n for n in ast.walk(transformed) if isinstance(n, ast.YieldFrom)]
    assert not yield_from_nodes, "YieldFrom node should be removed after transformation"

    # The transformed code should contain a while loop (generated by the transformer)
    code = ast_to_code(transformed)
    assert "while" in code, "Transformed code should contain a while loop"
    assert "x" in code, "Variable 'x' should be present in the transformed code"

def test_yield_from_expression_transforms():
    # Original code with a yield-from as a standalone expression
    source = "yield from iterable"
    tree = ast.parse(source)
    transformer = YieldFromTransformer()
    transformed = transformer.visit(tree)

    # No YieldFrom nodes should remain
    yield_from_nodes = [n for n in ast.walk(transformed) if isinstance(n, ast.YieldFrom)]
    assert not yield_from_nodes, "YieldFrom node should be removed after transformation"

    # The transformed code should contain a while loop
    code = ast_to_code(transformed)
    assert "while" in code, "Transformed code should contain a while loop"

def test_no_yield_from_remains_unchanged():
    # Code without any yield-from should stay unchanged
    source = "a = 1\nb = 2"
    tree = ast.parse(source)
    transformer = YieldFromTransformer()
    transformed = transformer.visit(tree)

    # The transformed tree should be structurally identical to the original
    original_code = ast_to_code(tree)
    transformed_code = ast_to_code(transformed)
    assert original_code == transformed_code, "Code without yield-from should remain unchanged"
