 if result['suite_pass']:
  covdest=dest/'coverage_export';covdest.mkdir();cp=process([t['python'],'-m','coverage','json','-o',str(dest/'coverage.json')],dest,env,covdest)
  if cp['returncode']==0:
   cov=read(dest/'coverage.json');counts=cov['totals'];result['coverage_counts']=counts
   if counts['num_statements']:result['line_pct']=100*counts['covered_lines']/counts['num_statements']
   if counts['num_branches']:result['branch_pct']=100*counts['covered_branches']/counts['num_branches']
